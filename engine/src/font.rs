/// Glyph rows for ASCII 0x20..0x7E (FONT8X8_BASIC is indexed from space);
/// anything else renders as '?'.
pub fn glyph(ch: char) -> &'static [u8; 8] {
    let idx = (ch as u32).wrapping_sub(0x20) as usize;
    if idx < FONT8X8_BASIC.len() {
        &FONT8X8_BASIC[idx]
    } else {
        &FONT8X8_BASIC['?' as usize - 0x20]
    }
}

/// Draw `text` into an RGBA8 buffer at (x, y), 8×8 glyphs × `scale`.
/// Only set-pixels are written (transparent pixels left untouched).
pub fn draw_text_rgba(
    buf: &mut [u8],
    w: u32,
    h: u32,
    text: &str,
    mut x: i32,
    y: i32,
    color: [u8; 3],
    scale: u32,
) {
    for ch in text.chars() {
        if ch == '\n' {
            x = 0;
            continue;
        }
        stamp(buf, w, h, ch, x, y, color, scale);
        x += 8 * scale as i32;
    }
}

/// Draw `text` into a 0x00RRGGBB framebuffer at (x, y), 8×8 glyphs × `scale`.
pub fn draw_text_u32(
    buf: &mut [u32],
    w: u32,
    h: u32,
    text: &str,
    mut x: i32,
    y: i32,
    color: [u8; 3],
    scale: u32,
) {
    let c = (color[0] as u32) << 16 | (color[1] as u32) << 8 | color[2] as u32;
    for ch in text.chars() {
        if ch == '\n' {
            x = 0;
            continue;
        }
        let rows = glyph(ch);
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..8 {
                if bits & (1 << rx) == 0 {
                    continue;
                }
                for sy in 0..scale as i32 {
                    for sx in 0..scale as i32 {
                        let px = x + rx as i32 * scale as i32 + sx;
                        let py = y + ry as i32 * scale as i32 + sy;
                        if px < 0 || py < 0 || px >= w as i32 || py >= h as i32 {
                            continue;
                        }
                        buf[py as usize * w as usize + px as usize] = c;
                    }
                }
            }
        }
        x += 8 * scale as i32;
    }
}

/// Pixel width of a single text line at the given scale.
pub fn text_width(text: &str, scale: u32) -> i32 {
    text.chars().count() as i32 * 8 * scale as i32
}

fn stamp(buf: &mut [u8], w: u32, h: u32, ch: char, x: i32, y: i32, color: [u8; 3], scale: u32) {
    let rows = glyph(ch);
    for (ry, bits) in rows.iter().enumerate() {
        for rx in 0..8 {
            if bits & (1 << rx) == 0 {
                continue;
            }
            for sy in 0..scale as i32 {
                for sx in 0..scale as i32 {
                    let px = x + rx as i32 * scale as i32 + sx;
                    let py = y + ry as i32 * scale as i32 + sy;
                    if px < 0 || py < 0 || px >= w as i32 || py >= h as i32 {
                        continue;
                    }
                    let o = (py as u32 * w + px as u32) as usize * 4;
                    buf[o] = color[0];
                    buf[o + 1] = color[1];
                    buf[o + 2] = color[2];
                    buf[o + 3] = 255;
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bang_glyph_is_16_pixels() {
        // '!' rows: 0x18,0x3C,0x3C,0x18,0x18,0x00,0x18,0x00 → 2+4+4+2+2+0+2 = 16
        let lit: usize = glyph('!').iter().map(|r| r.count_ones() as usize).sum();
        assert_eq!(lit, 16);
    }

    #[test]
    fn text_u32_renders_pixels() {
        let (w, h) = (16u32, 8u32);
        let mut buf = vec![0u32; (w * h) as usize];
        draw_text_u32(&mut buf, w, h, "!", 0, 0, [255, 0, 0], 1);
        assert_eq!(buf.iter().filter(|&&p| p == 0xFF0000).count(), 16);
        // bit 0 = leftmost: '!' = 0x18 lights bits 3,4 → first lit pixel at (3,0)
        assert_eq!(buf[3], 0xFF0000);
        assert_eq!(buf[0], 0);
    }

    #[test]
    fn unknown_char_is_question_mark() {
        let (w, h) = (8u32, 8u32);
        let mut buf = vec![0u8; (w * h * 4) as usize];
        draw_text_rgba(&mut buf, w, h, "\u{e9}", 0, 0, [0, 255, 0], 1);
        assert!(buf.chunks(4).any(|p| p[1] == 255), "é renders as '?'");
    }
}
